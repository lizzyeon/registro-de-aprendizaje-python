# 슬라이싱 [시작 : 끝 : 간격]
# [:]    -> 처음부터 끝까지              12345[:]    -> 12345
# [::1]  -> 원래 그대로                  12345[::1]  -> 12345
# [::2]  -> 앞에서부터 2칸씩             12345[::2]  -> 135
# [::-1] -> 뒤에서부터 1칸씩             12345[::-1] -> 54321
# [::-2] -> 뒤에서부터 2칸씩             12345[::-1] -> 531


