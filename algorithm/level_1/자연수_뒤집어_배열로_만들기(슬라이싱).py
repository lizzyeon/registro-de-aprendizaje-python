# 수정 풀이

def solution(n):
  N = str(n)                   # N = n.split()   이걸 쓰면 그냥 리스트가 되는 줄..
  chars = list(N)              # 옆의 두 줄처럼 문자열로 바꿔서 리스트로 바꿔야 한다

  a = ""

  for i in chars:
    a = i + a                  # 평소 사용했던 a = a + i와는 다름. 이건 뒤집기!
                               # 기존 a의 앞쪽에 다음 i를 붙이는 방

  return list(map(int, a))


